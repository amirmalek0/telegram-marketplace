// Derive trusted, local SVG sprites from the pinned Lucide package. No runtime CDN.
// Emits apply_patch input; pass --part=N (0=contracts, 1..N=sprite chunks).
import { readdir, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const dir = new URL('backoffice/node_modules/lucide-react/dist/esm/icons/', root);
const icons = [];
for (const file of (await readdir(dir)).filter(x => x.endsWith('.mjs')).sort()) {
  const source = await readFile(new URL(file, dir), 'utf8');
  if (!source.includes('const __iconNode =')) continue; // Exclude deprecated aliases.
  const { __iconNode: nodes } = await import(new URL(file, dir));
  icons.push({ name: file.slice(0, -4), nodes });
}
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
const chunks = [];
for (let start = 0; start < icons.length; start += 64) {
  const symbols = icons.slice(start, start + 64).map(({ name, nodes }) => {
    const children = nodes.map(([tag, attrs]) => {
      if (!['path','circle','rect','line','polyline','polygon','ellipse'].includes(tag)) throw Error('Unexpected SVG tag');
      return `<${tag} ${Object.entries(attrs).filter(([key]) => key !== 'key').map(([key, value]) => `${key}="${escape(value)}"`).join(' ')}/>`;
    }).join('');
    return `<symbol id="${name}" viewBox="0 0 24 24">${children}</symbol>`;
  }).join('\n');
  const body = `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols}\n</svg>\n`;
  chunks.push({ file: `lucide-${createHash('sha256').update(body).digest('hex').slice(0, 12)}.svg`, body });
}
if (process.argv.includes('--count')) { console.log(JSON.stringify({ icons: icons.length, parts: chunks.length + 1 })); process.exit(0); }
const part = Number(process.argv.find(x => x.startsWith('--part='))?.split('=')[1] ?? 0);
const files = [];
if (part === 0) {
  const catalog = `// Generated by tools/generate-icon-catalog.mjs from Lucide. Do not edit by hand.\nexport const catalogIconNames: readonly string[] = ${JSON.stringify(icons.map(x => x.name))};\nconst sprites: readonly string[] = ${JSON.stringify(chunks.map(x => x.file))};\nexport type CatalogIconName = \`lucide:\${string}\`;\nconst indices = new Map(catalogIconNames.map((name, index) => ['lucide:' + name, index]));\nexport function isCatalogIcon(value: unknown): value is CatalogIconName { return typeof value === 'string' && indices.has(value); }\nexport function catalogIconHref(value: string): string | undefined {\n  const index = indices.get(value);\n  return index === undefined ? undefined : '/icons/' + sprites[Math.floor(index / 64)] + '#' + catalogIconNames[index];\n}\n`;
  files.push(['backoffice/src/pages/miniapp-content/iconCatalog.ts', catalog], ['miniapp/src/features/content/iconCatalog.ts', catalog]);
  files.push(['core/internal/core/settings/icon_catalog.txt', icons.map(x => 'lucide:' + x.name).join('\n') + '\n']);
  const license = await readFile(new URL('backoffice/node_modules/lucide-react/LICENSE', root), 'utf8');
  for (const app of ['backoffice','miniapp']) files.push([`${app}/public/icons/LICENSE.txt`, license]);
} else {
  const chunk = chunks[part - 1];
  if (!chunk) throw Error('Unknown part');
  for (const app of ['backoffice','miniapp']) files.push([`${app}/public/icons/${chunk.file}`, chunk.body]);
}
console.log('*** Begin Patch\n' + files.map(([file, body]) => `*** Add File: ${file}\n` + body.trimEnd().split('\n').map(line => '+' + line).join('\n')).join('\n') + '\n*** End Patch');
