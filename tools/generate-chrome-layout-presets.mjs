// Source of truth for structural chrome presets. Run from any working directory.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const header = [
  ['masthead','نشان مرکزی','لوگو و عنوان وسط، ابزارها در ردیف جدا'],
  ['utility','نوار ابزار بالا','ابزارها بالا، عنوان بزرگ در ردیف پایین'],
  ['console','کنسول کناری','نام فروشگاه در یک ستون و ابزارها در ستون دیگر'],
  ['balanced','عنوان میان ابزارها','عنوان وسط و ابزارها در دو سمت آن'],
  ['banner','بنر فروشگاه','عنوان برجسته و سه ابزار تمام‌عرض زیر آن'],
  ['split','دو پنل','کارت برند و شبکه ابزارها در دو پنل مستقل'],
  ['portrait','لوگوی بزرگ','لوگوی بزرگ کنار عنوان و نوار ابزار زیر برند'],
  ['ribbon','روبان ابزار','عنوان ساده با ابزارهای متصل در انتهای ردیف دوم'],
  ['compact','ردیف معکوس','ابزارها در ابتدا و برند در انتهای یک ردیف'],
  ['corner','گوشه باز','عنوان و لوگو در دو گوشه با ابزارها در گوشه پایین'],
];
const navigation = [
  ['stack','ستونی','آیکون بالا و عنوان پایین با نشانگر انتخاب مستقل'],
  ['inline','افقی','آیکون و متن کنار هم؛ در تعداد زیاد به دو ردیف می‌رود'],
  ['expand','گزینه بازشونده','گزینه فعال پهن می‌شود و عنوان آن کنار آیکون می‌آید'],
  ['reverse','عنوان بالا','عنوان‌ها بالای آیکون‌ها قرار می‌گیرند'],
  ['bubbles','دکمه‌های جدا','هر گزینه یک دکمه مستقل با عنوان زیر آن است'],
  ['lift','گزینه برجسته','دکمه فعال بالاتر از نوار قرار می‌گیرد'],
  ['splitdock','داک دو قسمتی','گزینه‌ها با فاصله مرکزی در دو گروه قرار می‌گیرند'],
  ['folders','زبانه‌ها','گزینه فعال مانند زبانه بالای بدنه نوار می‌آید'],
  ['launcher','شبکه میانبر','گزینه‌ها به شکل میانبرهای دو ردیفه نمایش داده می‌شوند'],
  ['labelrail','نوار عنوان','ردیف آیکون‌ها با عنوان فعال در نوار زیر آن'],
];
const headerVariants = [['tiles','کاشی'],['pills','کپسول'],['rules','خطی'],['circles','دایره'],['tags','برچسب']];
const navVariants = [['plate','صفحه فعال'],['ring','حلقه'],['marker','نشانگر'],['lozenge','لوزی نرم'],['bracket','براکت']];
const records = (families,variants) => Object.fromEntries(families.flatMap(([family,label,description]) => variants.map(([variant,variantLabel]) => [`${family}-${variant}`,{family,variant,label:`${label} · ${variantLabel}`,description}])));
const entries = {header:records(header,headerVariants),navigation:records(navigation,navVariants)};
const json = value => JSON.stringify(value,null,2);
let ts = '// Generated by tools/generate-chrome-layout-presets.mjs. Do not edit by hand.\n';
ts += 'export interface ChromeLayoutPreset { family: string; variant: string; label: string; description: string }\n';
for (const [kind,families] of [['header',header],['navigation',navigation]]) {
  ts += `export const ${kind}LayoutFamilies = ${json(families.map(([id,label,description])=>({id,label,description})))} as const;\n`;
  ts += `export const ${kind}LayoutPresetIds = ${json(Object.keys(entries[kind]))} as const;\n`;
  ts += `export const ${kind}LayoutPresets: Record<string, ChromeLayoutPreset> = ${json(entries[kind])};\n`;
}
for (const path of ['miniapp/src/features/content/chromeLayoutPresets.ts','backoffice/src/pages/miniapp-content/chromeLayoutPresets.ts']) writeFileSync(new URL(path,root),ts);
let go = '// Code generated by tools/generate-chrome-layout-presets.mjs; DO NOT EDIT.\npackage settings\n';
for (const kind of ['header','navigation']) go += `\nvar ${kind}LayoutThemeNames = []string{\n${Object.keys(entries[kind]).map(id=>'\t'+JSON.stringify(id)+',').join('\n')}\n}\n`;
writeFileSync(new URL('core/internal/core/settings/chrome_layout_presets.go',root),go);
const css = readFileSync(new URL('tools/chrome-layout-presets.css',root),'utf8');
for(const path of ['miniapp/src/styles/chrome-layout-presets.css','backoffice/src/pages/miniapp-content/chrome-layout-presets.css']) writeFileSync(new URL(path,root),'/* Generated copy: edit tools/chrome-layout-presets.css and run the generator. */\n'+css);
console.log('Generated 50 header and 50 navigation structural presets and shared rendering styles.');
